"""Проверка заглушки systemd-resolved в link-watch: без сети."""
import asyncio

import pytest

from conftest import load

plat = load("plat_stub_mod", "platform_support.py")
check_pairs = load("check_pairs_stub_mod", "check_pairs.py")


@pytest.mark.parametrize("content, expected", [
    ("nameserver 127.0.0.53\noptions edns0 trust-ad\nsearch .\n", True),   # Ubuntu
    ("# Generated by Docker\nnameserver 192.168.65.7\n", False),          # Docker
    ("nameserver 10.0.0.1\nnameserver 8.8.8.8\n", False),                 # Alpine, OpenWrt
    ("# nameserver 127.0.0.53\nnameserver 1.1.1.1\n", False),             # закомментировано
    ("", False),
])
def test_uses_resolved_stub(tmp_path, monkeypatch, content, expected):
    monkeypatch.setattr(plat, "IS_LINUX", True)
    resolv = tmp_path / "resolv.conf"
    resolv.write_text(content, encoding="utf-8")
    assert plat.uses_resolved_stub(str(resolv)) is expected


def test_no_resolv_conf_means_no_stub(tmp_path, monkeypatch):
    monkeypatch.setattr(plat, "IS_LINUX", True)
    assert plat.uses_resolved_stub(str(tmp_path / "missing")) is False


def test_not_linux_means_no_stub(monkeypatch):
    monkeypatch.setattr(plat, "IS_LINUX", False)
    assert plat.uses_resolved_stub() is False


@pytest.mark.parametrize("stub, expected_dns_tcp", [
    (False, None),   # Linux без systemd-resolved: не проверяем, а не «false»
    (True, True),
])
def test_link_probe_checks_stub_only_when_configured(monkeypatch, stub, expected_dns_tcp):
    """Раньше dns_tcp на любом Linux проверял 127.0.0.53 и без systemd-resolved
    всегда был false — канал выглядел наполовину мёртвым."""
    asked = []

    class Writer:
        def close(self):
            pass

        async def wait_closed(self):
            pass

    async def fake_open_connection(host, port, **kwargs):
        asked.append(host)
        return None, Writer()

    monkeypatch.setattr(check_pairs, "BIND_INTERFACE", "")
    monkeypatch.setattr(check_pairs.plat, "uses_resolved_stub", lambda path="": stub)
    monkeypatch.setattr(check_pairs.asyncio, "open_connection", fake_open_connection)
    result = asyncio.run(check_pairs.link_probe(None, timeout=0.1))
    assert result["dns_tcp"] is expected_dns_tcp
    assert ("127.0.0.53" in asked) is stub
